def yaml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def safe_paragraph_text(paragraph) -> str:
    def walk(node) -> str:
        if node.tag in {qn("m:oMath"), qn("m:oMathPara"), qn("w:object")}:
            return "【公式见教材原文】"
        if node.tag == qn("w:t"):
            return node.text or ""
        return "".join(walk(child) for child in node)

    return "".join(walk(child) for child in paragraph._p)


def excerpt(paragraphs, start: int, end: int) -> str:
    """Keep a short, intact textbook passage for human review."""
    parts = []
    for paragraph in paragraphs[start:end]:
        line = " ".join(safe_paragraph_text(paragraph).split())
        if line == "【公式见教材原文】":
            parts.append(line)
            continue
        if len(line) < 35 or re.fullmatch(r"[图表]\d+(?:\.\d+)?\s+.{1,45}", line) or line.startswith(("注：", "参考文献")):
            continue
        sentences = re.split(r"(?<=[。！？])", line)
        for sentence in sentences:
            if sentence and len("".join(parts)) + len(sentence) <= 650:
                parts.append(sentence)
            if len("".join(parts)) >= 300:
                break
        if len("".join(parts)) >= 300:
            break
    return " ".join(parts).strip()


